/**
 * Distinctive product-subject terms of a question, bounded for SQL. `exclude`
 * holds option values the planner already extracted and the store's field
 * labels ("ความจุ", "รสชาติ"): they qualify a variant, never pick a product.
 */
export function productContentTerms(
  query: string,
  exclude: readonly (string | null | undefined)[] = [],
): string[] {
  const excluded = new Set(
    exclude.flatMap((value) => (value ? thaiTerms(value) : [])),
  );
  return [...new Set(thaiTerms(query))]
    .filter(
      (term) =>
        !QUESTION_TERMS.has(term) &&
        !FUNCTION_WORDS.has(term) &&
        !excluded.has(term) &&
        !/^\d+$/u.test(term),
    )
    .slice(0, 12);
}
